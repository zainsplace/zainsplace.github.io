#!/usr/bin/env python3
"""Regenerate data_inline.js from the data/<unit>/*.json files.
Run:  python build_inline.py
Edit the JSON under data/unit1, data/unit2 or data/shared, then re-run this
to update the site. (Flashcards: edit tools/make_flashcards.py and run it first.)

Units are the two exam components:
  u1 = Component 1 (Varieties of film and filmmaking): sections a, b, c + k
  u2 = Component 2 (Global filmmaking perspectives):   sections a, b + k
Section k is the shared Film Toolkit (data/shared/k.json), included in both.

Output shape:
  const INLINE_UNITS = {
    "u1": { "sections": {"a": {...}, ...}, "flashcards": {...},
            "questions": {...}, "extended": [...], "lessons": {...} },
    "u2": { ... }
  };
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, 'data')

UNITS = {
    'u1': ['a', 'b', 'c', 'k'],
    'u2': ['a', 'b', 'k'],
}

FOLDER = {'u1': 'unit1', 'u2': 'unit2'}
SHARED = {'k'}


def load_path(path):
    with open(path, encoding='utf-8') as f:
        return json.load(f)


def load(unit, name):
    folder = 'shared' if name in SHARED else FOLDER[unit]
    return load_path(os.path.join(DATA, folder, name + '.json'))


def items_with_topic(section):
    """Yield (topic_title, item) for every notes item in a section."""
    for topic in section.get('topics', []):
        for sub in topic.get('subtopics', []):
            for it in sub.get('items', []):
                if it.get('code') and it.get('term') and it.get('definition'):
                    yield topic.get('title', ''), it


def short_topic(title):
    # "Casablanca (Curtiz, 1942) — Classical Hollywood" -> "Casablanca"
    return title.split(' (')[0].split(' — ')[0].split(':')[0].strip()


def auto_cards(sections):
    """One recall card per notes item, so every term is drilled by Leitner review."""
    out = []
    for letter, sec in sections.items():
        for topic_title, it in items_with_topic(sec):
            topic = short_topic(topic_title)
            term = it['term']
            front = term if term.lower().startswith(topic.lower()) else '%s — %s' % (topic, term)
            out.append({'id': 'i' + it['code'], 'section': letter.upper(), 'code': it['code'],
                        'front': front + ': what is it and why does it matter?',
                        'back': it['definition'], 'auto': True})
    return out


def build_unit(unit):
    sections = {letter: load(unit, letter) for letter in UNITS[unit]}
    cards = load(unit, 'flashcards')
    cards = {'cards': cards['cards'] + auto_cards(sections)}
    return {
        'sections': sections,
        'flashcards': cards,
        'questions': load(unit, 'questions'),
        'extended': load(unit, 'extended'),
        'lessons': load_lessons(unit),
    }


def load_lessons(unit):
    """Scenario questions for the Sections path, keyed by spec code.
    One optional file per section: data/<unit>/lessons/<letter>.json."""
    out = {}
    for letter in UNITS[unit]:
        folder = 'shared' if letter in SHARED else FOLDER[unit]
        path = os.path.join(DATA, folder, 'lessons', letter + '.json')
        if os.path.exists(path):
            out.update(load_path(path))
    return out


if __name__ == '__main__':
    payload = {unit: build_unit(unit) for unit in UNITS}
    body = json.dumps(payload, ensure_ascii=False, indent=1)
    out = (
        '/* AUTO-GENERATED by build_inline.py: edit the JSON under data/ then re-run */\n\n'
        'const INLINE_UNITS = ' + body + ';\n'
    )
    with open(os.path.join(HERE, 'data_inline.js'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(out)
    for u in payload:
        n_items = sum(1 for s in payload[u]['sections'].values() for _ in items_with_topic(s))
        print('%s: %d notes items, %d flashcards, %d exam questions, %d extended prompts'
              % (u, n_items, len(payload[u]['flashcards']['cards']),
                 len(payload[u]['questions'].get('questions', [])), len(payload[u]['extended'])))
    print('data_inline.js regenerated (%d KB)' % (len(out.encode('utf-8')) // 1024))
